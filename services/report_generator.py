    @classmethod
    def build_unified_report(cls, dataset_name: Optional[str] = None) -> UnifiedReport:
        """Collect actual analysis results from session state and construct a UnifiedReport.

        Strictly incorporates only sections for which actual analysis has occurred.
        Never fabricates or creates demo data.
        """
        from core.session_manager import SessionManager

        if not SessionManager.is_dataset_loaded():
            target_name = dataset_name or "dataset.csv"
            return UnifiedReport(dataset_name=target_name)

        active_name = (
            dataset_name
            or SessionManager.get_active_dataset_name()
            or SessionManager.get_dataset_name()
            or "dataset.csv"
        )
        active_df = SessionManager.get_dataset_by_name(active_name)
        if active_df is None:
            active_df = SessionManager.get_active_df()
        if active_df is None:
            active_df = pd.DataFrame()

        file_type = (
            SessionManager.get("dataset_types", {}).get(active_name)
            or SessionManager.get_dataset_type()
            or "CSV"
        )

        # 1. Dataset Information Section
        dataset_info = DatasetInfoSection(
            dataset_name=active_name,
            file_type=file_type,
            rows=len(active_df),
            columns=len(active_df.columns),
            analysis_time=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        )

        report = UnifiedReport(
            dataset_name=active_name,
            dataset_info=dataset_info,
        )

        # 2. Data Profile (only if actual profile exists)
        prof = SessionManager.get_profile(filename=active_name)
        if not prof:
            prof = SessionManager.get_all_profiles().get(active_name)

        if prof:
            col_items: List[ColumnProfileItem] = []
            raw_cols = getattr(prof, "columns", {})
            if isinstance(raw_cols, dict):
                for c_name, c_prof in raw_cols.items():
                    col_items.append(
                        ColumnProfileItem(
                            name=str(c_name),
                            dtype=str(getattr(c_prof, "dtype", "")),
                            semantic_type=str(getattr(c_prof, "semantic_type", "UNKNOWN")),
                            missing_count=int(getattr(c_prof, "missing_count", 0)),
                            missing_percentage=float(getattr(c_prof, "missing_percentage", 0.0)),
                            unique_count=int(getattr(c_prof, "unique_count", 0)),
                            unique_percentage=float(getattr(c_prof, "unique_percentage", 0.0)),
                            numeric_stats=getattr(c_prof, "numeric_stats", None),
                        )
                    )

            q_report = getattr(prof, "quality", None)
            report.profile = DataProfileSection(
                total_rows=int(getattr(prof, "total_rows", len(active_df))),
                total_columns=int(getattr(prof, "total_columns", len(active_df.columns))),
                total_missing=int(getattr(prof, "total_missing", 0)),
                missing_percentage=float(getattr(prof, "missing_percentage", 0.0)),
                duplicate_rows=int(getattr(prof, "duplicate_rows", 0)),
                duplicate_percentage=float(getattr(prof, "duplicate_percentage", 0.0)),
                type_counts=getattr(prof, "type_counts", {}),
                health_score=getattr(q_report, "health_score", None) if q_report else None,
                health_status=getattr(q_report, "health_status", None) if q_report else None,
                health_explanation=getattr(q_report, "health_explanation", None) if q_report else None,
                columns=col_items,
            )

        # 3. Cleaning Summary (only if actual cleaning summary exists)
        cleaning_summaries = SessionManager.get("dataset_cleaning_summaries", {})
        summary = cleaning_summaries.get(active_name) or SessionManager.get("cleaning_summary")
        if summary and (hasattr(summary, "changes_applied") or hasattr(summary, "before_rows")):
            b_rows = int(getattr(summary, "before_rows", len(active_df)))
            a_rows = int(getattr(summary, "after_rows", len(active_df)))
            b_cols = int(getattr(summary, "before_columns", len(active_df.columns)))
            a_cols = int(getattr(summary, "after_columns", len(active_df.columns)))
            b_miss = int(getattr(summary, "before_missing", 0))
            a_miss = int(getattr(summary, "after_missing", 0))
            b_dups = int(getattr(summary, "before_duplicates", 0))
            a_dups = int(getattr(summary, "after_duplicates", 0))
            changes = list(getattr(summary, "changes_applied", []))

            modified_cols = set()
            for log in getattr(summary, "log_entries", []):
                if isinstance(log, dict) and log.get("column"):
                    modified_cols.add(str(log["column"]))

            report.cleaning = CleaningSection(
                before_rows=b_rows,
                after_rows=a_rows,
                before_columns=b_cols,
                after_columns=a_cols,
                missing_handled=max(0, b_miss - a_miss),
                duplicates_handled=max(0, b_dups - a_dups),
                columns_modified=sorted(list(modified_cols)),
                rows_affected=abs(b_rows - a_rows),
                changes_applied=changes,
                timestamp=str(getattr(summary, "timestamp", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))),
            )

        # 4. Anomaly Summary (only if actual anomaly results exist)
        all_anomalies = SessionManager.get_all_anomaly_results()
        ds_anomalies = all_anomalies.get(active_name) or SessionManager.get_anomaly_results(active_name)
        if ds_anomalies and isinstance(ds_anomalies, dict):
            methods_list: List[AnomalyMethodResult] = []
            unique_anom_indices = set()
            has_indices = False
            fallback_tot = 0

            if "iqr" in ds_anomalies:
                iqr_r = ds_anomalies["iqr"]
                cnt = int(getattr(iqr_r, "total_outlier_rows", 0))
                fallback_tot = max(fallback_tot, cnt)
                iqr_idxs = getattr(iqr_r, "all_outlier_indices", None)
                if iqr_idxs is not None:
                    unique_anom_indices.update(iqr_idxs)
                    has_indices = True
                methods_list.append(
                    AnomalyMethodResult(
                        method=f"IQR Outlier Detection ({getattr(iqr_r, 'multiplier', 1.5)}×)",
                        anomalies_detected=cnt,
                        anomaly_percentage=float(getattr(iqr_r, "outlier_rate", 0.0)),
                        features_used=list(getattr(iqr_r, "columns_analyzed", [])),
                        details=f"{len(getattr(iqr_r, 'column_results', {}))} feature(s) evaluated",
                    )
                )
            if "isolation_forest" in ds_anomalies:
                if_r = ds_anomalies["isolation_forest"]
                cnt = int(getattr(if_r, "anomaly_count", 0))
                fallback_tot = max(fallback_tot, cnt)
                if_idxs = getattr(if_r, "anomaly_indices", None)
                if if_idxs is not None:
                    unique_anom_indices.update(if_idxs)
                    has_indices = True
                methods_list.append(
                    AnomalyMethodResult(
                        method="Isolation Forest (Unsupervised)",
                        anomalies_detected=cnt,
                        anomaly_percentage=float(getattr(if_r, "anomaly_pct", 0.0)),
                        features_used=list(getattr(if_r, "features_used", [])),
                        details=f"Contamination: {getattr(if_r, 'contamination', 0.05)}",
                    )
                )
            if "multivariate" in ds_anomalies:
                mv_r = ds_anomalies["multivariate"]
                cnt = int(getattr(mv_r, "anomaly_count", 0))
                fallback_tot = max(fallback_tot, cnt)
                mv_idxs = getattr(mv_r, "all_anomaly_indices", None)
                if mv_idxs is not None:
                    unique_anom_indices.update(mv_idxs)
                    has_indices = True
                methods_list.append(
                    AnomalyMethodResult(
                        method="Multivariate Relationship Analysis",
                        anomalies_detected=cnt,
                        anomaly_percentage=float(getattr(mv_r, "anomaly_pct", 0.0)),
                        features_used=list(getattr(mv_r, "features_used", [])),
                        details="Joint feature covariance analysis",
                    )
                )

            tot_anom = len(unique_anom_indices) if has_indices else fallback_tot

            treatment_str = None
            if "last_treatment" in ds_anomalies:
                treat = ds_anomalies["last_treatment"]
                treatment_str = f"{getattr(treat, 'treatment_type', '').upper()}: {getattr(treat, 'details', '')}"

            if methods_list:
                report.anomaly = AnomalySection(
                    methods=methods_list,
                    total_anomalies=tot_anom,
                    treatment_applied=treatment_str,
                )

        # 5. Prediction / Forecast Summary (only if actual prediction results exist)
        pred_res = SessionManager.get_prediction_result(active_name)
        if not pred_res:
            all_preds = SessionManager.get_all_prediction_results()
            pred_res = all_preds.get(active_name)

        if pred_res and getattr(pred_res, "status", None) == "success":
            p_type = str(getattr(pred_res, "problem_type", "")).lower()
            mode_val = str(getattr(pred_res, "mode", "")).lower()
            is_forecast = "forecast" in p_type or mode_val == "forecasting" or "time_series" in p_type

            raw_pts = getattr(pred_res, "predictions", []) or []
            pts_list = []
            for pt in raw_pts:
                pts_list.append({
                    "period": getattr(pt, "index_or_date", ""),
                    "predicted_value": getattr(pt, "predicted_value", None),
                    "actual_value": getattr(pt, "actual_value", None),
                    "lower_bound": getattr(pt, "lower_bound", None),
                    "upper_bound": getattr(pt, "upper_bound", None),
                })

            b_metrics = getattr(pred_res, "best_metrics", None)
            metrics_dict = b_metrics.to_dict() if hasattr(b_metrics, "to_dict") else {}

            top_feats = []
            if getattr(pred_res, "feature_importance", None):
                top_feats = [getattr(f, "feature", str(f)) for f in pred_res.feature_importance[:5]]

            if is_forecast:
                report.forecast = ForecastSection(
                    time_column=getattr(pred_res, "date_column", None) or "Time Period",
                    target=getattr(pred_res, "target_column", "Target"),
                    model=getattr(pred_res, "selected_model_name", "Forecasting Model"),
                    forecast_horizon=int(getattr(pred_res, "forecast_horizon", len(pts_list)) or len(pts_list)),
                    frequency=getattr(pred_res, "frequency", None),
                    forecast_results=pts_list,
                )
            else:
                report.prediction = PredictionSection(
                    target=getattr(pred_res, "target_column", "Target"),
                    problem_type=getattr(pred_res, "problem_type", mode_val).replace("_", " ").title(),
                    selected_model=getattr(pred_res, "selected_model_name", "Prediction Model"),
                    metrics=metrics_dict,
                    prediction_count=len(pts_list),
                    predictions=pts_list,
                    top_features=top_feats,
                )

        # 6. Ask Analyst Summary (only if questions were actually asked)
        ask_hist = SessionManager.get("ask_analyst_history", [])
        if ask_hist and isinstance(ask_hist, list):
            q_items: List[AskAnalystQueryItem] = []
            for item in ask_hist:
                if isinstance(item, dict):
                    q_text = item.get("question") or item.get("original_question")
                    ans_payload = item.get("answer", {})
                    ans_text = ans_payload.get("answer", "") if isinstance(ans_payload, dict) else str(ans_payload)
                    conf = ans_payload.get("confidence", "High") if isinstance(ans_payload, dict) else "High"
                    q_plan = item.get("query_plan", {})
                    intent = q_plan.get("intent", "") if isinstance(q_plan, dict) else ""
                    if q_text and ans_text:
                        q_items.append(
                            AskAnalystQueryItem(
                                question=str(q_text),
                                answer=str(ans_text),
                                confidence=str(conf),
                                intent=str(intent),
                                timestamp=str(item.get("timestamp", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))),
                            )
                        )
            if q_items:
                report.ask_analyst = AskAnalystSection(queries=q_items)

        return report

